"""Write EFFICIENCY.md: tokens and wall-clock per run, and per solved test, for both benchmarks.

Usage: python3 efficiency.py   (from the repo root; reads */runs/*/timing.json etc.)

Tokens are what the model generated (Ollama eval_count / OpenAI completion_tokens, so a
thinking model's reasoning counts). "Tokens per solved test" = generated tokens / tests
passed (coding, of 23) or puzzles correct (reasoning, of 12); a run that solved nothing
has no value there. Scores are the automatic ones (grade.py / pytest); RESULTS.md notes
the few grade.py false negatives.
"""
import glob
import json
import os
import re

HEADER = """# Efficiency: tokens and time per solved test

Generated by `efficiency.py` from every run directory (`*/runs/*`); re-run it after
new results. Tokens = tokens the model generated (reasoning included); wall-clock =
the whole request as the benchmark saw it. "Tok/solved" divides tokens by tests passed
(coding, of 23) or puzzles correct (reasoning, of 12). Scores are the automatic ones;
see RESULTS.md for the hardware, quant and the few grade.py false negatives.
Runs that are still in progress (no `timing.json` yet) are left out.

"""


def wall(d):
    try:
        m = re.search(r"wall_clock_seconds=(\d+)", open(os.path.join(d, "wall_clock.txt")).read())
        return int(m.group(1)) if m else None
    except OSError:
        return None


def score(bench, d):
    try:
        if bench == "coding":
            m = re.search(r"(\d+) passed", open(os.path.join(d, "pytest_result.txt")).read())
            return int(m.group(1)) if m else 0
        m = re.search(r"(\d+)/12", open(os.path.join(d, "grade_result.txt")).read())
        return int(m.group(1)) if m else None
    except OSError:
        return None


def table(bench, total):
    rows = []
    for d in glob.glob("%s-benchmark/runs/*" % bench):
        try:
            t = json.load(open(os.path.join(d, "timing.json")))
        except (OSError, ValueError):
            continue
        tok, s, w = t.get("eval_count"), score(bench, d), wall(d)
        if tok is None or s is None:
            continue
        rows.append((os.path.basename(d), tok, s, w, t.get("eval_tokens_per_s")))
    # solved runs first, most efficient (fewest tokens per solved test) on top
    rows.sort(key=lambda r: (r[2] == 0, r[1] / r[2] if r[2] else 0, r[0]))
    out = ["| Run | Score | Tokens | Tok/solved | Wall-clock | Tok/s |", "|---|---|---|---|---|---|"]
    for name, tok, s, w, tps in rows:
        per = "%d" % round(tok / s) if s else "—"
        wc = ("%dm %02ds" % divmod(w, 60) if w >= 60 else "%ds" % w) if w is not None else "—"
        out.append("| `%s` | %d/%d | %s | %s | %s | %s |" % (
            name, s, total, format(tok, ","), per, wc, "%.1f" % tps if tps else "—"))
    return "\n".join(out)


os.chdir(os.path.dirname(os.path.abspath(__file__)))
with open("EFFICIENCY.md", "w") as f:
    f.write(HEADER)
    f.write("## Coding (23 tests)\n\n" + table("coding", 23) + "\n\n")
    f.write("## Reasoning (12 puzzles)\n\n" + table("reasoning", 12) + "\n")
print("wrote EFFICIENCY.md")
